def computeDB(frag):
    if args.silence is None:
        return round(frag.dBFS, 1)
    chunks = split_on_silence(frag, min_silence_len=args.silenceLength, silence_thresh=args.silenceThreshold, keep_silence=False,
                    seek_step=args.silenceStep)
    if len(chunks) == 0 or len(chunks[0]) == len(frag):
        return None
    lFragment = AdSeg.empty()
    for c in chunks:
        lFragment += c
    return round(lFragment.dBFS, 1)

def decodeAccelerate(val:str):
    ma = ra = 0
    if not isEmpty(val):
        t = val.split(':')
        ma = float(t[0])
        if len(t) > 1 and not isEmpty(t[1]):
            ra = float(t[1])
            args.stretch = True
    return ma, ra

