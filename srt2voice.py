def isEmpty(s, attr: str = None) -> bool:
    if s and attr:
        s = getattr(s, attr, None)
    if not s:
        return True
    if type(s) is str:
        return s.isspace()
    elif type(s) in (int, float):
        return False
    return len(s) == 0

# Accelerate speech generated by Google (gTTS)
def changeSpeed(inFile: str, outFile: str, s_ratio: float, g_ratio: float):
    if s_ratio == 0:
        s_ratio = 1.0
    arguments = ["audio-stretch", "-q", "-y", "-r" + str(s_ratio)]
    if g_ratio != 1.0 and g_ratio != 0:
        arguments.append("-g" + str(g_ratio))
    arguments.append(inFile)
    arguments.append(outFile)
    rv = subprocess.run(arguments)
    return rv.returncode

