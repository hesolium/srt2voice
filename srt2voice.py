def keepFragment(idx, merged):
    rv = None
    if args.fragments is not None:
        idx1 = idx + 1
        if len(args.fragments) == 0 or idx1 in args.fragments:
            fn = getFragmentPrefix(idx, merged)
            # save generated fragment voice for subtitle
            if os.path.isfile(tmp_mp3):
                rv = fn + ".mp3"
                if os.path.isfile(rv):
                    os.remove(rv)
                os.rename(tmp_mp3, rv)
    return rv

def generate_gtts(text, outFile):
    if os.path.isfile(outFile):
        os.remove(outFile)
    maxTry = 3
    while maxTry > 0:
        try:
            sFrag = gTTS(text=text, lang=args.language, slow=False)
            sFrag.save(tmp_mp3)
            break
        except OSError:
            if not args.quiet:
                print("Network error! Sleep for 5 seconds and try again...")
            time.sleep(5)
            maxTry -= 1
            if maxTry == 0:
                print("Generating voice for '" + text + "' failed")
                sys.exit(1)

def createVoice(txt: str):
    if args.voiceGenerator is None:
        generate_gtts(txt, tmp_mp3)
    else:
        args.voiceGenerator.generateVoice(txt, tmp_mp3)
    sFrag = AdSeg.from_mp3(tmp_mp3)
    dur = len(sFrag)
    sFrag = trimSilence(sFrag)
    if len(sFrag) != dur:
        sFrag.export(tmp_mp3)
    return sFrag

def trimSilence(voice: AudioSegment):
    duration = len(voice)
    start = detect_leading_silence(voice)
    end = detect_leading_silence(voice.reverse())
    if start > 0 or end < duration:
        voice = voice[start:duration - end]
    return voice

# Generate speech from text.
def genFragment(txt: str, idx: int, merged: int):
    tmp3File = sFrag = None
    if os.path.isfile(tmp_mp3):
        os.remove(tmp_mp3)
    if args.usePreloaded:
        fn = getFragmentPrefix(idx, merged) + ".mp3"
        if os.path.isfile(fn):
            tmp3File = fn
    if tmp3File is None:
        # mp3 file not preloaded. Get speech from external source
        sFrag = createVoice(txt)
        fn = keepFragment(idx, merged)
        tmp3File = fn if fn is not None else tmp_mp3
    if not args.preloadOnly:
        if sFrag is None:
            sFrag = AdSeg.from_mp3(tmp3File)
        sFrag.export(tmp_wav, format="wav")
        if (args.accelerate != 0.0 and args.accelerate != 1.0) or (args.gapAccelerate != 0.0 and args.gapAccelerate != 1.0):
            changeSpeed(tmp_wav, tmp_wav2, args.accelerate, args.gapAccelerate)
            sFrag = AdSeg.from_wav(tmp_wav2)
    return sFrag

def getFragmentPrefix(idx: int, merged: int):
    idx1 = idx + 1
    fn = format(idx1, formatIdx)
    if merged > 0:
        fn += "-" + str(idx1 + merged)
    if args.subtitleBasename is not None:
        fn = args.subtitleBasename + "-" + fn
    fl = os.path.join(args.fragmentsDir, fn)
    return fl

def generateFragment(idx: int):
    global args, subs
    sb = getSubtitle(idx)
    txt = sb.text
    verbose("Subtitle", idx + 1, ':', txt)
    verbose("Time range: [", sb.start, ",", sb.end, "]  Duration:", sb.duration.ordinal, "ms")
    skipSub = 0
    sFrag = genFragment(txt, idx, skipSub)
    if args.preloadOnly:
        return None, 0, 0
    sb2 = getSubtitle(idx + 1)
    orgLen = len(sFrag)
    sgap = (sb2.start - sb.start).ordinal if sb2 else orgLen
    verbose("Speech segment len:", orgLen, "ms")
    if 0 < sgap < orgLen:
        # try to concatenate with next subtitle
        if sb2:
            txt2 = txt + ' ' + sb2.text
            skipSub = 1
            sFrag = genFragment(txt2, idx, skipSub)
            orgLen = len(sFrag)
            sb3 = getSubtitle(idx + 2)
            sgap = (sb3.start - sb.start).ordinal if sb3 else orgLen
            verbose("Gap too small. Concatenated sub:", txt2)
            verbose("Concatenated gap len:", sgap, "ms")
        if 0 < sgap < orgLen and (0 < args.minAccelerate < 1.0 or 0 < args.minGapAccelerate < 1.0):
            # concatenation failed. Speed up speech
            verbose("Concatenated speech too long (", orgLen, "ms). Speed up.")
            if args.accelerate != 0.0 and args.accelerate != 1.0:
                orgLen /= args.accelerate
            nRatio = max(round(sgap / orgLen, 2), args.minAccelerate)
            proc = (nRatio - args.minAccelerate) / (1.0 - args.minAccelerate)
            gRatio = args.minGapAccelerate + (1.0 - args.minGapAccelerate) * proc
            gRatio = max(round(gRatio, 2), args.minGapAccelerate)
            verbose("New accelerate ratio:", nRatio, "gap ratio:", gRatio)
            changeSpeed(tmp_wav, tmp_wav2, nRatio, gRatio)
            sFrag = AdSeg.from_wav(tmp_wav2)
        verbose("New speech segment len:", len(sFrag), "ms")
    return sFrag, sgap, skipSub

